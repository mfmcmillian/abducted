// Prepare the Earth-set models: every GLB in the Meshy download folder is optimised into
// models/earth/ (textures to 2048 px, light simplification) and src/client/earthManifest.ts is
// regenerated with each model's bounding box so the scene can scale and ground them.
//
// Run: node tools/earth-models.mjs [downloadDir]

import { execSync } from 'node:child_process'
import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

// @gltf-transform/core lives in the npx cache next to the CLI we already use
const NPX = process.env.LOCALAPPDATA.split('\\').join('/') + '/npm-cache/_npx/'
const cacheDir = readdirSync(NPX).map((d) => NPX + d + '/node_modules/@gltf-transform/core').find((p) => existsSync(p))
if (!cacheDir) throw new Error('run npx @gltf-transform/cli once to populate the cache')
const require = createRequire(cacheDir + '/package.json')
const { NodeIO, getBounds } = require(cacheDir)

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '..')
const IN = process.argv[2] ?? 'C:/Users/matth/Downloads/meshy-earth'
const OUT = join(ROOT, 'models', 'earth')
const MANIFEST = join(ROOT, 'src', 'client', 'earthManifest.ts')
mkdirSync(OUT, { recursive: true })

const SIMPLIFY = { house: 0.6, 'house-neighbour': 0.5, tv: 0.6, countryside: 0.6, city: 0.6 } // default 0.5
const TEX = { house: 2048, 'house-neighbour': 2048, tv: 2048, sofa: 2048, car: 2048, countryside: 2048, city: 2048 } // default 1024

const io = new NodeIO()
const entries = {}
for (const file of readdirSync(IN).filter((f) => f.endsWith('.glb'))) {
  const name = file.replace(/\.glb$/, '')
  const src = join(IN, file)
  const dst = join(OUT, file)
  if (!existsSync(dst) || statSync(dst).mtimeMs < statSync(src).mtimeMs) {
    const ratio = SIMPLIFY[name] ?? 0.5
    const tex = TEX[name] ?? 1024
    execSync(
      `npx --no-install @gltf-transform/cli optimize "${src}" "${dst}" --compress false --texture-compress auto --texture-size ${tex} --simplify true --simplify-ratio ${ratio} --simplify-error 0.0005 --join true --flatten true`,
      { stdio: 'ignore', cwd: ROOT }
    )
    // the hero house gets its picture window cut open again (the zoom flies in through it)
    if (name === 'house') execSync('node tools/cut-window.mjs', { stdio: 'inherit', cwd: ROOT })
    // the TV loses its baked glass dome; models/earth-screen.glb puts a recessed screen in the hole
    if (name === 'tv') execSync('node tools/cut-hole.mjs models/earth/tv.glb -0.82 0.44 -0.42 0.34 0.30', { stdio: 'inherit', cwd: ROOT })
  }
  const doc = await io.read(dst)
  const { min, max } = getBounds(doc.getRoot().listScenes()[0])
  const tris = doc
    .getRoot()
    .listMeshes()
    .reduce((n, m) => n + m.listPrimitives().reduce((k, p) => k + (p.getIndices()?.getCount() ?? p.getAttribute('POSITION').getCount()) / 3, 0), 0)
  entries[name] = { min: min.map((v) => +v.toFixed(3)), max: max.map((v) => +v.toFixed(3)) }
  console.log(name.padEnd(16), `${(statSync(dst).size / 1e6).toFixed(1)} MB`, `${Math.round(tris / 1000)}k tris`, 'size', max.map((v, i) => (v - min[i]).toFixed(2)).join(' x '))
}

const lines = Object.entries(entries)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, b]) => `  '${name}': { src: 'models/earth/${name}.glb', min: [${b.min.join(', ')}], max: [${b.max.join(', ')}] }`)
writeFileSync(
  MANIFEST,
  `// Generated by tools/earth-models.mjs: do not edit. Bounding boxes of the Meshy models in models/earth/.\nexport const EARTH_MODELS = {\n${lines.join(',\n')}\n} as const\nexport type EarthModel = keyof typeof EARTH_MODELS\n`
)
console.log('manifest:', Object.keys(entries).length, 'models')
