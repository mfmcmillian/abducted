/** Single looping VideoPlayer; every screen in the scene samples this entity. */
export function createVideoPlayer(): Entity {
  const video = engine.addEntity()
  Transform.create(video, { position: Vector3.create(CENTER.x, 10, CENTER.z) })
  VideoPlayer.create(video, {
    src: VIDEO_URL,
    playing: true,
    loop: true,
    volume: 0.8,
    playbackRate: 1
  })

  videoEventsSystem.registerVideoEventsEntity(video, (event) => {
    switch (event.state) {
      case VideoState.VS_READY:
        console.log('[dome] video ready')
        break
      case VideoState.VS_PLAYING:
        console.log('[dome] video playing')
        break
      case VideoState.VS_ERROR:
        console.log('[dome] video error')
        break
    }
  })

  return video
}

/**
 * The dome shell (models/dome.glb, generated by tools/build-dome.mjs). The two shell
 * nodes get their placeholder material swapped for an unlit video texture so the
 * music video wraps the whole interior and exterior.
 */
export function createDome(video: Entity): Entity {
  const dome = engine.addEntity()
  Transform.create(dome, { position: CENTER })
  GltfContainer.create(dome, {
    src: 'models/dome.glb',
    visibleMeshesCollisionMask: ColliderLayer.CL_PHYSICS,
    invisibleMeshesCollisionMask: ColliderLayer.CL_NONE
  })

  const videoTexture = Material.Texture.Video({
    videoPlayerEntity: video,
    wrapMode: TextureWrapMode.TWM_CLAMP,
    filterMode: TextureFilterMode.TFM_BILINEAR
  })
  const screenMaterial = {
    material: {
      $case: 'unlit' as const,
      unlit: {
        texture: videoTexture,
        diffuseColor: Color4.White(),
        castShadows: false
      }
    }
  }

  // Node paths match the node names written by tools/build-dome.mjs.
  GltfNodeModifiers.create(dome, {
    modifiers: [
      { path: 'DomeInner', material: screenMaterial, castShadows: false },
      { path: 'DomeOuter', material: screenMaterial, castShadows: false }
    ]
  })

  return dome
}

/**
 * Centre piece: the Abducted! emote props (UFO, beam, cow, pumpkin, grave) running
 * their 8 s prop animation on a loop, scaled up to fill the big room. Faces the door.
 */
export function createDiorama(): Entity {
  const props = engine.addEntity()
  Transform.create(props, {
    position: CENTER,
    rotation: Quaternion.fromEulerDegrees(0, 180, 0),
    scale: Vector3.create(2.5, 2.5, 2.5)
  })
  GltfContainer.create(props, {
    src: 'models/abducted_props.glb',
    visibleMeshesCollisionMask: ColliderLayer.CL_POINTER,
    invisibleMeshesCollisionMask: ColliderLayer.CL_NONE
  })
  Animator.create(props, {
    states: [{ clip: 'Abducted_Prop', playing: true, loop: true, speed: 1 }]
  })

  pointerEventsSystem.onPointerDown(
    { entity: props, opts: { button: InputAction.IA_POINTER, hoverText: 'They appear to be enjoying it', maxDistance: 24 } },
    () => {
      void openExternalUrl({ url: COSTUME_URL })
    }
  )

  return props
}

