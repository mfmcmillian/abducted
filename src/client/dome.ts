/** Single looping VideoPlayer; every screen in the scene samples this entity. */
export function createVideoPlayer(): Entity {
  const video = engine.addEntity()
  Transform.create(video, { position: Vector3.create(CENTER.x, 10, CENTER.z) })
  VideoPlayer.create(video, {
    src: VIDEO_URL,
    playing: true,
    loop: true,
    volume: 0.8,
    playbackRate: 1
  })

  videoEventsSystem.registerVideoEventsEntity(video, (event) => {
    switch (event.state) {
      case VideoState.VS_READY:
        console.log('[dome] video ready')
        break
      case VideoState.VS_PLAYING:
        console.log('[dome] video playing')
        break
      case VideoState.VS_ERROR:
        console.log('[dome] video error')
        break
    }
  })

  return video
}

/**
 * The dome shell (models/dome.glb, generated by tools/build-dome.mjs). The two shell
 * nodes get their placeholder material swapped for an unlit video texture so the
 * music video wraps the whole interior and exterior.
 */
export function createDome(video: Entity): Entity {
  const dome = engine.addEntity()
  Transform.create(dome, { position: CENTER })
  GltfContainer.create(dome, {
    src: 'models/dome.glb',
    visibleMeshesCollisionMask: ColliderLayer.CL_PHYSICS,
    invisibleMeshesCollisionMask: ColliderLayer.CL_NONE
  })

  const videoTexture = Material.Texture.Video({
    videoPlayerEntity: video,
    wrapMode: TextureWrapMode.TWM_CLAMP,
    filterMode: TextureFilterMode.TFM_BILINEAR
  })
  const screenMaterial = {
    material: {
      $case: 'unlit' as const,
      unlit: {
        texture: videoTexture,
        diffuseColor: Color4.White(),
        castShadows: false
      }
    }
  }

  // Floor: a quiet alien-terrain tile. The Floor node has planar UVs (one tile per 6 m);
  // MIRROR wrap guarantees no visible seams even if the tile is not perfectly seamless.
  const floorMaterial = {
    material: {
      $case: 'pbr' as const,
      pbr: {
        texture: Material.Texture.Common({
          src: 'images/dome-floor-tile.jpg',
          wrapMode: TextureWrapMode.TWM_MIRROR,
          filterMode: TextureFilterMode.TFM_TRILINEAR
        }),
        albedoColor: Color4.create(0.85, 1, 0.9, 1),
        metallic: 0,
        roughness: 1,
        specularIntensity: 0,
        castShadows: false
      }
    }
  }

  // Vertical wall under the video: a continuous observation deck. Machinery strips above and
  // below, glass between, and outside it dome.glb carries a 30 m deep star ring; the planets,
  // ships and rocks out there are models driven by src/client/space.ts. Same PBR-with-texture path as the floor (which the Explorer honours);
  // the emissive copy keeps everything readable in the dark. MIRROR wrap hides tile seams.
  const wallMaterialFor = (src: string, wrapMode: TextureWrapMode, emissiveIntensity = 0.9) => {
    const texture = Material.Texture.Common({ src, wrapMode, filterMode: TextureFilterMode.TFM_TRILINEAR })
    return {
      material: {
        $case: 'pbr' as const,
        pbr: {
          texture,
          emissiveTexture: texture,
          emissiveColor: Color3.White(),
          emissiveIntensity,
          albedoColor: Color4.White(),
          metallic: 0.2,
          roughness: 0.8,
          specularIntensity: 0,
          castShadows: false
        }
      }
    }
  }
  const machineMaterial = wallMaterialFor('images/ship-machines.jpg', TextureWrapMode.TWM_MIRROR)
  const starsMaterial = wallMaterialFor('images/space-stars.jpg', TextureWrapMode.TWM_MIRROR, 1)
  // The back wall is plain stars too: everything with a shape out there is a model (space.ts).
  const backdrops = [0, 1, 2, 3].map((i) => ({ path: 'SpaceBack' + i, material: starsMaterial, castShadows: false }))

  // The shell used to carry the video; it now plays on the TV inside the Earth (earthZoom.ts).
  // The dome is a dark machinery ceiling: the machines tile repeated around and up the shell.
  const ceilingTexture = Material.Texture.Common({ src: 'images/ship-machines.jpg', wrapMode: TextureWrapMode.TWM_MIRROR, filterMode: TextureFilterMode.TFM_TRILINEAR, tiling: { x: 16, y: 5 } })
  const ceilingMaterial = {
    material: {
      $case: 'pbr' as const,
      pbr: {
        texture: ceilingTexture,
        emissiveTexture: ceilingTexture,
        emissiveColor: Color3.create(0.55, 0.65, 0.75),
        emissiveIntensity: 0.35,
        albedoColor: Color4.create(0.35, 0.4, 0.45, 1),
        metallic: 0.4,
        roughness: 0.7,
        specularIntensity: 0,
        castShadows: false
      }
    }
  }
  void screenMaterial

  // Node paths match the node names written by tools/build-dome.mjs.
  GltfNodeModifiers.create(dome, {
    modifiers: [
      { path: 'DomeInner', material: ceilingMaterial, castShadows: false },
      { path: 'DomeOuter', material: ceilingMaterial, castShadows: false },
      { path: 'WallMachine', material: machineMaterial, castShadows: false },
      { path: 'SpaceStars', material: starsMaterial, castShadows: false },
      ...backdrops,
      { path: 'Floor', material: floorMaterial, castShadows: false }
    ]
  })

  return dome
}

/**
 * Centre piece: the Abducted! emote props (UFO, beam, cow, pumpkin, grave) running
 * their 8 s prop animation on a loop, scaled up to fill the big room. Faces the door.
 */
export function createDiorama(): Entity {
  const props = engine.addEntity()
  Transform.create(props, {
    position: CENTER,
    rotation: Quaternion.fromEulerDegrees(0, 180, 0),
    scale: Vector3.create(3.5, 3.5, 3.5)
  })
  // Purely decorative: no colliders, so it is neither clickable nor blocks the player.
  GltfContainer.create(props, {
    src: 'models/abducted_props.glb',
    visibleMeshesCollisionMask: ColliderLayer.CL_NONE,
    invisibleMeshesCollisionMask: ColliderLayer.CL_NONE
  })
  Animator.create(props, {
    states: [{ clip: 'Abducted_Prop', playing: true, loop: true, speed: 1 }]
  })

  return props
}

/**
 * Mothership parked under the apex: hides the pinch where the video UVs collapse to a point
 * and gives the room a ceiling piece. Slow spin, slight hover, lights pointing down.
 */
export function createApexUfo(): Entity {
  const SCALE = 12 // ufo.glb is 2.2 m across, 1.23 m tall, origin at the bottom
  const BASE_Y = 74 // bottom of the hull; the dome apex is at 82
  const ufo = engine.addEntity()
  Transform.create(ufo, { position: Vector3.create(CENTER.x, BASE_Y, CENTER.z), scale: Vector3.create(SCALE, SCALE, SCALE) })
  GltfContainer.create(ufo, {
    src: 'models/ufo.glb',
    visibleMeshesCollisionMask: ColliderLayer.CL_NONE,
    invisibleMeshesCollisionMask: ColliderLayer.CL_NONE
  })

  const glow = engine.addEntity()
  Transform.create(glow, { position: Vector3.create(CENTER.x, BASE_Y - 1, CENTER.z) })
  LightSource.create(glow, {
    active: true,
    color: Color3.create(0.45, 1, 0.55),
    intensity: 2500,
    range: 40,
    shadow: false,
    type: LightSource.Type.Point({})
  })

  let clock = 0
  engine.addSystem((dt) => {
    clock += dt
    const t = Transform.getMutable(ufo)
    t.rotation = Quaternion.fromEulerDegrees(Math.sin(clock * 0.5) * 1.5, clock * 6, Math.cos(clock * 0.4) * 1.5)
    t.position.y = BASE_Y + Math.sin(clock * 0.6) * 0.6
    LightSource.getMutable(glow).intensity = 2200 + Math.sin(clock * 1.7) * 500
  })
  return ufo
}

/** Fan-favourite cow, standing by the door and greeting whoever walks in. */
export function createHeroCow(): Entity {
  const cow = engine.addEntity()
  Transform.create(cow, {
    position: Vector3.create(SPAWN.x + 5, 0, SPAWN.z + 3),
    rotation: Quaternion.fromEulerDegrees(0, -120, 0),
    scale: Vector3.create(2, 2, 2)
  })
  GltfContainer.create(cow, {
    src: 'models/cow.glb',
    visibleMeshesCollisionMask: ColliderLayer.CL_PHYSICS | ColliderLayer.CL_POINTER,
    invisibleMeshesCollisionMask: ColliderLayer.CL_NONE
  })

  pointerEventsSystem.onPointerDown(
    { entity: cow, opts: { button: InputAction.IA_POINTER, hoverText: 'Moo.', maxDistance: 40 } },
    () => {
      moo(Vector3.create(SPAWN.x + 5, 1.5, SPAWN.z + 3))
      void openExternalUrl({ url: EMOTE_URL })
    }
  )

  return cow
}

const PALETTE = [
  Color3.create(0.35, 1, 0.45), // alien green
  Color3.create(0.45, 0.6, 1), // beam blue
  Color3.create(0.9, 0.3, 1), // purple
  Color3.create(1, 0.35, 0.35) // red
]

/**
 * Inside the dome: a ring of floor tiles around the diorama and four coloured lights
 * that follow the music (bass drives intensity, the hue walks on every beat).
 */
export function createInterior() {
  const ringRadius = 15
  const tiles: Entity[] = []
  const TILE_COUNT = 16
  for (let i = 0; i < TILE_COUNT; i++) {
    const a = (i / TILE_COUNT) * Math.PI * 2
    const tile = engine.addEntity()
    Transform.create(tile, {
      position: Vector3.create(CENTER.x + ringRadius * Math.sin(a), 0.06, CENTER.z + ringRadius * Math.cos(a)),
      rotation: Quaternion.fromEulerDegrees(0, (a * 180) / Math.PI, 0),
      scale: Vector3.create(3.4, 0.08, 1.6)
    })
    MeshRenderer.setBox(tile)
    Material.setPbrMaterial(tile, {
      albedoColor: Color4.create(0.05, 0.05, 0.08, 1),
      emissiveColor: PALETTE[i % PALETTE.length],
      emissiveIntensity: 1,
      roughness: 0.4
    })
    tiles.push(tile)
  }

  const lights: Entity[] = []
  for (let i = 0; i < 4; i++) {
    const a = (i / 4) * Math.PI * 2 + Math.PI / 4
    const light = engine.addEntity()
    Transform.create(light, { position: Vector3.create(CENTER.x + 12 * Math.sin(a), 10, CENTER.z + 12 * Math.cos(a)) })
    LightSource.create(light, {
      active: true,
      color: PALETTE[i],
      intensity: 1200,
      range: 32,
      shadow: false,
      type: LightSource.Type.Point({})
    })
    lights.push(light)
  }

  // Blue fill over the spawn circle.
  const door = engine.addEntity()
  Transform.create(door, { position: Vector3.create(SPAWN.x, 5, SPAWN.z) })
  LightSource.create(door, {
    active: true,
    color: Color3.create(0.45, 0.6, 1),
    intensity: 500,
    range: 14,
    shadow: false,
    type: LightSource.Type.Point({})
  })

  let hueStep = 0
  let tick = 0
  engine.addSystem((dt) => {
    if (music.beat) hueStep++
    tick += dt
    // Lights every frame (cheap), tiles at ~12 Hz.
    for (let i = 0; i < lights.length; i++) {
      const l = LightSource.getMutable(lights[i])
      l.intensity = 500 + 2600 * music.bass
      l.color = PALETTE[(i + hueStep) % PALETTE.length]
    }
    if (tick < 1 / 12) return
    tick = 0
    for (let i = 0; i < tiles.length; i++) {
      const band = music.bands[i % 8]
      const m = Material.getMutable(tiles[i])
      if (m.material?.$case !== 'pbr') continue
      m.material.pbr.emissiveColor = PALETTE[(i + hueStep) % PALETTE.length]
      m.material.pbr.emissiveIntensity = 0.3 + 2 * band
    }
  })
}
