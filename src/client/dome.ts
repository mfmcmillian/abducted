const PALETTE = [
  Color3.create(0.35, 1, 0.45), // alien green
  Color3.create(0.45, 0.6, 1), // beam blue
  Color3.create(0.9, 0.3, 1), // purple
  Color3.create(1, 0.35, 0.35) // red
]

/**
 * Inside the dome: a ring of floor tiles around the diorama and four coloured lights
 * that follow the music (bass drives intensity, the hue walks on every beat).
 */
export function createInterior() {
  const ringRadius = 11
  const tiles: Entity[] = []
  const TILE_COUNT = 16
  for (let i = 0; i < TILE_COUNT; i++) {
    const a = (i / TILE_COUNT) * Math.PI * 2
    const tile = engine.addEntity()
    Transform.create(tile, {
      position: Vector3.create(CENTER.x + ringRadius * Math.sin(a), 0.06, CENTER.z + ringRadius * Math.cos(a)),
      rotation: Quaternion.fromEulerDegrees(0, (a * 180) / Math.PI, 0),
      scale: Vector3.create(2.6, 0.08, 1.4)
    })
    MeshRenderer.setBox(tile)
    Material.setPbrMaterial(tile, {
      albedoColor: Color4.create(0.05, 0.05, 0.08, 1),
      emissiveColor: PALETTE[i % PALETTE.length],
      emissiveIntensity: 1,
      roughness: 0.4
    })
    tiles.push(tile)
  }

  const lights: Entity[] = []
  for (let i = 0; i < 4; i++) {
    const a = (i / 4) * Math.PI * 2 + Math.PI / 4
    const light = engine.addEntity()
    Transform.create(light, { position: Vector3.create(CENTER.x + 8 * Math.sin(a), 7, CENTER.z + 8 * Math.cos(a)) })
    LightSource.create(light, {
      active: true,
      color: PALETTE[i],
      intensity: 600,
      range: 18,
      shadow: false,
      type: LightSource.Type.Point({})
    })
    lights.push(light)
  }

  // Blue fill at the door so the entrance reads from outside.
  const door = engine.addEntity()
  Transform.create(door, { position: Vector3.create(DOOR.x, 4, DOOR.z - 1) })
  LightSource.create(door, {
    active: true,
    color: Color3.create(0.45, 0.6, 1),
    intensity: 400,
    range: 10,
    shadow: false,
    type: LightSource.Type.Point({})
  })

  let hueStep = 0
  let tick = 0
  engine.addSystem((dt) => {
    if (music.beat) hueStep++
    tick += dt
    // Lights every frame (cheap), tiles at ~12 Hz.
    for (let i = 0; i < lights.length; i++) {
      const l = LightSource.getMutable(lights[i])
      l.intensity = 250 + 1400 * music.bass
      l.color = PALETTE[(i + hueStep) % PALETTE.length]
    }
    if (tick < 1 / 12) return
    tick = 0
    for (let i = 0; i < tiles.length; i++) {
      const band = music.bands[i % 8]
      const m = Material.getMutable(tiles[i])
      if (m.material?.$case !== 'pbr') continue
      m.material.pbr.emissiveColor = PALETTE[(i + hueStep) % PALETTE.length]
      m.material.pbr.emissiveIntensity = 0.3 + 2 * band
    }
  })
}

