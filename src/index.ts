import {
  Animator,
  ColliderLayer,
  engine,
  GltfContainer,
  GltfNodeModifiers,
  InputAction,
  LightSource,
  Material,
  pointerEventsSystem,
  TextureFilterMode,
  TextureWrapMode,
  Transform,
  videoEventsSystem,
  VideoPlayer,
  VideoState
} from '@dcl/sdk/ecs'
import { Color3, Color4, Quaternion, Vector3 } from '@dcl/sdk/math'
import { openExternalUrl } from '~system/RestrictedActions'

// "They appear to be enjoying it" music video, 720p30, hosted on the KOA Firebase project bucket.
const VIDEO_URL = 'https://storage.googleapis.com/koa-db-media/alien-dome/enjoying-720p.mp4'

// Abducted! emote collection (Red / Purple / Green / Cyan) and the alien costume wearables.
const EMOTE_COLLECTION = '0x95e2e9e7e8796e79fd7ebeff5b7ddc9879fbbc88'
const COSTUME_COLLECTION = '0x36a8a03f5c048953b0ceda9e05755df3f1004ae8'
const EMOTE_URL = `https://decentraland.org/marketplace/contracts/${EMOTE_COLLECTION}/items/2`
const COSTUME_URL = `https://decentraland.org/marketplace/contracts/${COSTUME_COLLECTION}/items/0`

const CENTER = Vector3.create(8, 0, 8)

export function main() {
  const video = createVideoPlayer()
  createDome(video)
  createDiorama()
  createHeroCow()
  createLights()
}

/** Single looping VideoPlayer; every screen in the scene samples this entity. */
function createVideoPlayer() {
  const video = engine.addEntity()
  Transform.create(video, { position: Vector3.create(CENTER.x, 3, CENTER.z) })
  VideoPlayer.create(video, {
    src: VIDEO_URL,
    playing: true,
    loop: true,
    volume: 0.8,
    playbackRate: 1
  })

  videoEventsSystem.registerVideoEventsEntity(video, (event) => {
    switch (event.state) {
      case VideoState.VS_READY:
        console.log('[dome] video ready')
        break
      case VideoState.VS_PLAYING:
        console.log('[dome] video playing')
        break
      case VideoState.VS_ERROR:
        console.log('[dome] video error')
        break
    }
  })

  return video
}

/**
 * The dome shell (models/dome.glb, generated by tools/build-dome.mjs). The two shell
 * nodes get their placeholder material swapped for an unlit video texture so the
 * music video wraps the whole interior and exterior.
 */
function createDome(video: ReturnType<typeof engine.addEntity>) {
  const dome = engine.addEntity()
  Transform.create(dome, { position: CENTER })
  GltfContainer.create(dome, {
    src: 'models/dome.glb',
    visibleMeshesCollisionMask: ColliderLayer.CL_PHYSICS,
    invisibleMeshesCollisionMask: ColliderLayer.CL_NONE
  })

  const videoTexture = Material.Texture.Video({
    videoPlayerEntity: video,
    wrapMode: TextureWrapMode.TWM_CLAMP,
    filterMode: TextureFilterMode.TFM_BILINEAR
  })
  const screenMaterial = {
    material: {
      $case: 'unlit' as const,
      unlit: {
        texture: videoTexture,
        diffuseColor: Color4.White(),
        castShadows: false
      }
    }
  }

  // Node paths match the node names written by tools/build-dome.mjs.
  GltfNodeModifiers.create(dome, {
    modifiers: [
      { path: 'DomeInner', material: screenMaterial, castShadows: false },
      { path: 'DomeOuter', material: screenMaterial, castShadows: false }
    ]
  })

  return dome
}

/**
 * Centre piece: the Abducted! emote props (UFO, beam, cow, pumpkin, grave) running
 * their 8 s prop animation on a loop. Faces the south door.
 */
function createDiorama() {
  const props = engine.addEntity()
  Transform.create(props, {
    position: CENTER,
    rotation: Quaternion.fromEulerDegrees(0, 180, 0)
  })
  GltfContainer.create(props, {
    src: 'models/abducted_props.glb',
    visibleMeshesCollisionMask: ColliderLayer.CL_POINTER,
    invisibleMeshesCollisionMask: ColliderLayer.CL_NONE
  })
  Animator.create(props, {
    states: [{ clip: 'Abducted_Prop', playing: true, loop: true, speed: 1 }]
  })

  pointerEventsSystem.onPointerDown(
    { entity: props, opts: { button: InputAction.IA_POINTER, hoverText: 'They appear to be enjoying it', maxDistance: 12 } },
    () => {
      void openExternalUrl({ url: COSTUME_URL })
    }
  )

  return props
}

/** Fan-favourite cow, standing by the door and greeting whoever walks in. */
function createHeroCow() {
  const cow = engine.addEntity()
  Transform.create(cow, {
    position: Vector3.create(10.6, 0, 3.4),
    rotation: Quaternion.fromEulerDegrees(0, -120, 0),
    scale: Vector3.create(1.6, 1.6, 1.6)
  })
  GltfContainer.create(cow, {
    src: 'models/cow.glb',
    visibleMeshesCollisionMask: ColliderLayer.CL_PHYSICS | ColliderLayer.CL_POINTER,
    invisibleMeshesCollisionMask: ColliderLayer.CL_NONE
  })

  pointerEventsSystem.onPointerDown(
    { entity: cow, opts: { button: InputAction.IA_POINTER, hoverText: 'Moo.', maxDistance: 8 } },
    () => {
      void openExternalUrl({ url: EMOTE_URL })
    }
  )

  return cow
}

/** A green glow under the saucer and a cool fill by the door; the video does the rest. */
function createLights() {
  const beam = engine.addEntity()
  Transform.create(beam, { position: Vector3.create(CENTER.x, 2.5, CENTER.z) })
  LightSource.create(beam, {
    active: true,
    color: Color3.create(0.35, 1, 0.45),
    intensity: 900,
    range: 7,
    shadow: false,
    type: LightSource.Type.Point({})
  })

  const door = engine.addEntity()
  Transform.create(door, { position: Vector3.create(8, 3.2, 2.2) })
  LightSource.create(door, {
    active: true,
    color: Color3.create(0.45, 0.6, 1),
    intensity: 300,
    range: 5,
    shadow: false,
    type: LightSource.Type.Point({})
  })
}
